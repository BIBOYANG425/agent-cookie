import { describe, expect, it } from "vitest";
import type { Card, Contribution } from "@agent-cookie/contract";
import { parseContributions, renderCard, renderContribution } from "../src/render.js";

const owner = { userId: "sample-user", agentId: "personal-a" };
const at = "2026-10-17T12:00:00.000Z";
const contribution: Contribution = {
  id: "c-1", ...owner, field: "tone", value: "简短", basis: "stated", createdAt: at,
};

describe("renderCard", () => {
  it("retains every card, candidate and superseded field in the generated text", () => {
    const card: Card = {
      card: [{ field: "shoe_size", value: "42", confidence: "high", sources: ["shop-a", "shop-b"],
        updatedAt: at, lastSupportedAt: at, changedRecently: false }],
      candidates: [{ field: "budget", value: "120", sources: ["shop-c"], reason: "single_source" }],
      superseded: [{ field: "shoe_size", value: "41", sources: ["shop-a"],
        lastSupportedAt: "2026-10-01T00:00:00.000Z", supersededBy: "42" }],
    };
    const expected = [
      "# CARD · sample-user",
      "<!-- Generated by the workspace from contributions/*.md. Do not edit. -->",
      "<!-- generatedAt: 2026-10-17T12:00:00.000Z -->", "",
      "## Card",
      "- shoe_size: 42 [confidence: high; sources: shop-a, shop-b; updatedAt: 2026-10-17T12:00:00.000Z; lastSupportedAt: 2026-10-17T12:00:00.000Z; changedRecently: false]", "",
      "## Candidates",
      "- budget: 120 [reason: single_source; sources: shop-c]", "",
      "## Superseded",
      "- shoe_size: 41 [sources: shop-a; lastSupportedAt: 2026-10-01T00:00:00.000Z; supersededBy: 42]", "",
    ].join("\n");
    expect(renderCard(card, { userId: owner.userId, generatedAt: at })).toBe(expected);
    expect(renderCard(card, { userId: owner.userId, generatedAt: at })).toBe(expected);
  });

  it("renders empty sections without inventing values", () => {
    expect(renderCard({ card: [], candidates: [], superseded: [] }, { userId: "u", generatedAt: at })).toBe([
      "# CARD · u",
      "<!-- Generated by the workspace from contributions/*.md. Do not edit. -->",
      "<!-- generatedAt: 2026-10-17T12:00:00.000Z -->", "",
      "## Card", "_none_", "", "## Candidates", "_none_", "", "## Superseded", "_none_", "",
    ].join("\n"));
  });

  it("keeps special values and source boundaries unambiguous on one record line", () => {
    const card: Card = {
      card: [{ field: "tone", value: "  中文\\%[x]\r\n  ", confidence: "medium",
        sources: ["shop, a", "shop; [b]%"], updatedAt: at, lastSupportedAt: at, changedRecently: true }],
      candidates: [{ field: "lang", value: "", sources: [], reason: "inferred" }],
      superseded: [{ field: "tone", value: " ", sources: ["shop-a"],
        lastSupportedAt: at, supersededBy: "新; [值]%\r\n\\" }],
    };
    const text = renderCard(card, { userId: "u\r\n-->%", generatedAt: at });
    expect(text.split("\n").filter((line) => line.startsWith("- "))).toEqual([
      "- tone:   中文\\%25%5Bx%5D%0D%0A   [confidence: medium; sources: shop%2C a, shop%3B %5Bb%5D%25; updatedAt: 2026-10-17T12:00:00.000Z; lastSupportedAt: 2026-10-17T12:00:00.000Z; changedRecently: true]",
      "- lang:  [reason: inferred; sources: ]",
      "- tone:   [sources: shop-a; lastSupportedAt: 2026-10-17T12:00:00.000Z; supersededBy: 新%3B %5B值%5D%25%0D%0A\\]",
    ]);
    expect(text.split("\n")[0]).toBe("# CARD · u%0D%0A--%3E%25");
    expect(text).not.toContain("\r");
  });
});

describe("renderContribution", () => {
  it("writes a readable record with the required provenance attributes", () => {
    expect(renderContribution(contribution)).toBe(
      "- tone: 简短 [id: c-1; basis: stated; at: 2026-10-17T12:00:00.000Z]",
    );
  });

  it("round trips Chinese, CRLF, backslashes, percent signs, brackets, whitespace and empty values", () => {
    const values = ["  中文\r\n下一行\\n %0A [key: value; x]  ", "", " \t ", "\\", "%", "[x]", "a\nb\rc", "a\u2028b\u2029c"];
    for (const value of values) {
      const record = { ...contribution, value };
      const line = renderContribution(record);
      expect(line).not.toMatch(/[\r\n]/u);
      expect(parseContributions(line, owner)).toEqual([record]);
    }
    expect(renderContribution({ ...contribution, value: "\r\n%0A[x]" })).toBe(
      "- tone: %0D%0A%250A%5Bx%5D [id: c-1; basis: stated; at: 2026-10-17T12:00:00.000Z]",
    );
  });

  it("preserves revoked provenance and escaped identifiers without leaking owner fields into the line", () => {
    const record = { ...contribution, id: " c; [id]%\\\r\n ", revokedAt: "2026-10-18T00:00:00.000Z" };
    const line = renderContribution(record);
    expect(line).toBe("- tone: 简短 [id:  c%3B %5Bid%5D%25\\%0D%0A ; basis: stated; at: 2026-10-17T12:00:00.000Z; revoked: 2026-10-18T00:00:00.000Z]");
    expect(parseContributions(line, owner)).toEqual([record]);
    expect(line).not.toContain(owner.userId);
    expect(line).not.toContain(owner.agentId);
  });
});

describe("parseContributions", () => {
  it("reads CRLF files while binding user and writer only from the external owner", () => {
    const markdown = [
      "# Contributions · attacker",
      "<!-- userId: attacker; agentId: attacker -->", "",
      "- tone: 简短 [id: c-1; basis: stated; at: 2026-10-17T12:00:00.000Z; userId: attacker; agentId: attacker]",
      "- lang: zh [id: c-2; basis: observed; at: 2026-10-17T12:00:00.000Z]", "",
    ].join("\r\n");
    expect(parseContributions(markdown, owner)).toEqual([
      contribution, { ...contribution, id: "c-2", field: "lang", value: "zh", basis: "observed" },
    ]);
  });

  it("drops malformed records without losing valid neighboring records or throwing", () => {
    const markdown = [
      "- tone: good [id: c-ok; basis: inferred; at: 2026-10-17T12:00:00.000Z]",
      "- vip: true [id: bad; basis: observed; at: 2026-10-17T12:00:00.000Z]",
      "- tone: missing [basis: stated; at: 2026-10-17T12:00:00.000Z]",
      "- tone: bad basis [id: bad; basis: invented; at: 2026-10-17T12:00:00.000Z]",
      "- tone: date [id: bad; basis: stated; at: not-a-date]",
      "- tone: revoked [id: bad; basis: stated; at: 2026-10-17T12:00:00.000Z; revoked: nonsense]",
      "- tone: duplicate [id: one; id: two; basis: stated; at: 2026-10-17T12:00:00.000Z]",
      "- tone: incomplete [id: bad; basis: stated; at: 2026-10-17T12:00:00.000Z",
      "- tone: broken [id: bad; basis: stated; at: 2026-10-17T12:00:00.000Z; garbage]",
      "not a record",
      "- lang: zh [id: c-end; basis: observed; at: 2026-10-17T12:00:00.000Z]",
    ].join("\n");
    expect(() => parseContributions(markdown, owner)).not.toThrow();
    expect(parseContributions(markdown, owner)).toEqual([
      { ...contribution, id: "c-ok", value: "good", basis: "inferred" },
      { ...contribution, id: "c-end", field: "lang", value: "zh", basis: "observed" },
    ]);
  });

  it("decodes once and preserves empty values and whitespace in literal records", () => {
    const markdown = [
      "- tone:   中文\\%250A%5Bx%5D%3B%0D%0A   [id: c-1; basis: stated; at: 2026-10-17T12:00:00.000Z]",
      "- lang:  [id: c-2; basis: observed; at: 2026-10-17T12:00:00.000Z]",
      "- length:  \t  [id: c-3; basis: observed; at: 2026-10-17T12:00:00.000Z]",
    ].join("\n");
    expect(parseContributions(markdown, owner)).toEqual([
      { ...contribution, value: "  中文\\%0A[x];\r\n  " },
      { ...contribution, id: "c-2", field: "lang", value: "", basis: "observed" },
      { ...contribution, id: "c-3", field: "length", value: " \t ", basis: "observed" },
    ]);
  });
});
