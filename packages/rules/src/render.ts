import { isField, type Contribution, type RulesApi } from "@agent-cookie/contract";

// One physical line per record. Percent escapes protect grammar delimiters and CR/LF;
// Unicode, backslashes, empty strings and leading/trailing whitespace remain data.
// Decode exactly once: a literal "%0A" is written "%250A", never mistaken for LF.
function escapeText(value: string): string {
  return value.replace(/[%\r\n\[\];]/gu, percent);
}

function percent(character: string): string {
  return `%${character.charCodeAt(0).toString(16).toUpperCase().padStart(2, "0")}`;
}

function unescapeText(value: string): string {
  return value.replace(/%(25|0D|0A|5B|5D|3B|2C|3C|3E)/giu,
    (_, hex: string) => String.fromCharCode(Number.parseInt(hex, 16)));
}

type Attribute = readonly [key: string, value: string | readonly string[] | undefined];

function record(field: string, value: string, attributes: readonly Attribute[]): string {
  const parts: string[] = [];
  for (const [key, item] of attributes) {
    if (item === undefined) continue;
    // Escape each source before joining, so commas within an ID cannot add sources.
    const encoded = typeof item === "string" ? escapeText(item)
      : item.map((source) => escapeText(source).replace(/,/gu, percent)).join(", ");
    parts.push(`${key}: ${encoded}`);
  }
  return `- ${field}: ${escapeText(value)} [${parts.join("; ")}]`;
}

function headerText(value: string): string {
  return escapeText(value).replace(/[<>]/gu, percent);
}

export const renderCard: RulesApi["renderCard"] = (card, meta) => {
  const section = (name: string, lines: string[]): string =>
    `## ${name}\n${lines.length === 0 ? "_none_" : lines.join("\n")}`;
  return [
    `# CARD · ${headerText(meta.userId)}`,
    "<!-- Generated by the workspace from contributions/*.md. Do not edit. -->",
    `<!-- generatedAt: ${headerText(meta.generatedAt)} -->`, "",
    section("Card", card.card.map((field) => record(field.field, field.value, [
      ["confidence", field.confidence], ["sources", field.sources],
      ["updatedAt", field.updatedAt], ["lastSupportedAt", field.lastSupportedAt],
      ["changedRecently", String(field.changedRecently)],
    ]))), "",
    section("Candidates", card.candidates.map((candidate) => record(candidate.field, candidate.value, [
      ["reason", candidate.reason], ["sources", candidate.sources],
    ]))), "",
    section("Superseded", card.superseded.map((field) => record(field.field, field.value, [
      ["sources", field.sources], ["lastSupportedAt", field.lastSupportedAt],
      ["supersededBy", field.supersededBy],
    ]))), "",
  ].join("\n");
};

export const renderContribution: RulesApi["renderContribution"] = (contribution) => record(
  contribution.field, contribution.value, [
    ["id", contribution.id], ["basis", contribution.basis],
    ["at", contribution.createdAt], ["revoked", contribution.revokedAt],
  ],
);

function parseAttributes(block: string): Map<string, string> | undefined {
  const attributes = new Map<string, string>();
  for (const part of block.split("; ")) {
    const match = /^([A-Za-z][A-Za-z0-9]*): (.*)$/su.exec(part);
    if (!match || attributes.has(match[1]!)) return undefined;
    attributes.set(match[1]!, unescapeText(match[2]!));
  }
  return attributes;
}

function isTimestamp(value: string | undefined): value is string {
  return value !== undefined && value.length > 0 && Number.isFinite(Date.parse(value));
}

export const parseContributions: RulesApi["parseContributions"] = (markdown, owner) => {
  const contributions: Contribution[] = [];
  for (const line of markdown.split(/\r\n|\n|\r/u)) {
    // The required final attribute block disambiguates values that contain ": ".
    // Do not trim: the spaces on either side of the value can belong to the value.
    const match = /^- ([a-z_]+): (.*) \[([^\[\]\r\n]*)\]$/su.exec(line);
    if (!match || !isField(match[1])) continue;
    const attributes = parseAttributes(match[3]!);
    if (!attributes) continue;
    const id = attributes.get("id");
    const basis = attributes.get("basis");
    const createdAt = attributes.get("at");
    const revokedAt = attributes.get("revoked");
    if (!id || !isTimestamp(createdAt)) continue;
    if (basis !== "observed" && basis !== "stated" && basis !== "inferred") continue;
    if (revokedAt !== undefined && !isTimestamp(revokedAt)) continue;
    const contribution: Contribution = {
      id, userId: owner.userId, agentId: owner.agentId,
      field: match[1], value: unescapeText(match[2]!), basis, createdAt,
    };
    if (revokedAt !== undefined) contribution.revokedAt = revokedAt;
    contributions.push(contribution);
  }
  return contributions;
};
