export const messages = { zh, en };
export type MessageKey = keyof typeof zh;

let cardLocale: Locale = 'zh';
const storageKey = 'agent-cookie-console-locale';
const readOverride = (): Locale | undefined => {
  try { const stored = globalThis.localStorage?.getItem(storageKey); return stored === 'zh' || stored === 'en' ? stored : undefined; }
  catch { return undefined; }
};
let override = readOverride();
const listeners = new Set<() => void>();
export const getLocale = (): Locale => override ?? cardLocale;
export const getLocaleOverride = () => override;
export const subscribeLocale = (listener: () => void) => { listeners.add(listener); return () => { listeners.delete(listener); }; };
export const localeFromLang = (lang?: string): Locale => /^zh/i.test(lang ?? '') ? 'zh' : 'en';
export function setCardLanguage(lang?: string) {
  const previous = getLocale(); cardLocale = localeFromLang(lang);
  if (getLocale() !== previous) listeners.forEach(listener => listener());
}
export function setLocaleOverride(locale?: Locale) {
  override = locale;
  try { if (locale) globalThis.localStorage?.setItem(storageKey, locale); else globalThis.localStorage?.removeItem(storageKey); } catch { /* Storage can be disabled. */ }
  listeners.forEach(listener => listener());
}
export const dateLocale = () => getLocale() === 'zh' ? 'zh-CN' : 'en-US';
export const t = (key: MessageKey, ...values: Array<string | number>): string =>
  messages[getLocale()][key].replace(/\{(\d+)\}/g, (_, index: string) => String(values[Number(index)] ?? ''));

/** Relabel authored Sample/status text retained across a locale switch; never apply to user field values or evidence. */
export function localizeUiText(text: string): string {
  for (const locale of ['zh', 'en'] as const) {
    const entry = (Object.keys(messages[locale]) as MessageKey[]).find(key => messages[locale][key] === text);
    if (entry) return t(entry);
  }
  return text;
}
